async function initiateCheckout() {
    if (cart.length === 0) {
        alert("Your cart is empty!");
        return;
    }

    const totalAmount = cart.reduce((sum, item) => sum + (item.product.price * item.quantity), 0);
    
    // --- IMPORTANT: Replace this URL with YOUR actual server endpoint ---
    const SERVER_ENDPOINT = 'http://your-server-url.com/create-payment-intent'; 

    try {
        const response = await fetch(SERVER_ENDPOINT, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({ amountInCents: Math.round(totalAmount * 100) })
        });

        const data = await response.json();

        if (data.error) {
            throw new Error(data.error);
        }

        // SUCCESS! Now, redirect the user to Stripe's hosted payment page
        const { clientSecret } = data;
        const stripe = Stripe('YOUR_STRIPE_PUBLIC_KEY'); // You need your public key here

        const paymentIntent = await stripe.confirmCardPayment(clientSecret, {
            payment_method: {
                card: 'card_token_placeholder' // This token is generated by Stripe when the user enters their card details
            }
        });

        if (paymentIntent.status === 'succeeded') {
            alert("Payment Successful! Your digital products are being prepared for download.");
            cart = []; // Clear cart on success
            updateCartCount();
            renderCart(); // Refresh the cart page view
            // In a real app, you would now trigger file delivery here.
        } else {
            alert("Payment failed. Please try again.");
        }

    } catch (error) {
        console.error("Checkout Error:", error);
        alert(`Checkout Failed: ${error.message}. Please try again later.`);
    }
}


// Attach the new function to the checkout button on cart.html
document.addEventListener('DOMContentLoaded', () => {
    // ... (Existing setup code) ...

    const checkoutBtn = document.getElementById('checkoutBtn');
    if (checkoutBtn) {
        checkoutBtn.addEventListener('click', initiateCheckout);
    }
});
